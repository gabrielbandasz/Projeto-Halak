   private void carregarPedidosDoCliente(int idCliente) {
    try {
        PedidoDAO pedidoDAO = new PedidoDAO();
        List<Pedido> listaPedidos = pedidoDAO.listarPedidosPorCliente(idCliente);

        DefaultTableModel modelo = (DefaultTableModel) tabelaPedidos.getModel();
        modelo.setRowCount(0); // Limpa a tabela antes de carregar os dados

        for (Pedido pedido : listaPedidos) {
            String dataFormatada = new SimpleDateFormat("dd/MM/yyyy").format(pedido.getDataPedido());
            modelo.addRow(new Object[]{
                pedido.getIdPedido(),
                dataFormatada,
                pedido.getQuantidade(),
pedido.getValorTotal()
            });
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Erro ao carregar pedidos do cliente: " + e.getMessage());
        e.printStackTrace();
    }
}



