    private void btnDetalhesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetalhesActionPerformed

        int linhaSelecionada = tabelaPedidos.getSelectedRow(); // Obtém a linha selecionada

        if (linhaSelecionada == -1) { // Verifica se uma linha foi selecionada
            JOptionPane.showMessageDialog(this, "Selecione um pedido para ver os detalhes.");
            return; // Sai do método se nenhuma linha foi selecionada
        }

        // Obtém o ID do pedido da linha selecionada
        int idPedido = (int) tabelaPedidos.getValueAt(linhaSelecionada, 0);

        try {
            PedidoDAO pedidoDAO = new PedidoDAO();
            Pedido pedido = pedidoDAO.listarPedidosPorCliente(idCliente).stream()
                    .filter(p -> p.getIdPedido() == idPedido)
                    .findFirst()
                    .orElse(null); // Busca o pedido pelo ID

            if (pedido != null) {
                // Usa o novo construtor com modo de visualização ativado
                TelaComprasCliente tela = new TelaComprasCliente(pedido, true);
                tela.setVisible(true);
                this.dispose(); // Fecha a tela atual, se necessário
            } else {
                JOptionPane.showMessageDialog(this, "Pedido não encontrado.");
            }
        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Erro ao buscar os dados do pedido.");
        }


    }//GEN-LAST:event_btnDetalhesActionPerformed

