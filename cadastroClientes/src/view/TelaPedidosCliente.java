    private void excluirPedidoSelecionadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_excluirPedidoSelecionadoActionPerformed
   int linhaSelecionada = tabelaPedidos.getSelectedRow();

    if (linhaSelecionada == -1) {
        JOptionPane.showMessageDialog(this, "Selecione um pedido para excluir.");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(this,
            "Deseja realmente excluir este pedido e todos os seus produtos?", "Confirmação", JOptionPane.YES_NO_OPTION);

    if (confirm == JOptionPane.YES_OPTION) {
        try {
            // Pega o ID do pedido da primeira coluna
            int idPedidoSelecionado = (int) tabelaPedidos.getValueAt(linhaSelecionada, 0);

            PedidoDAO pedidoDAO = new PedidoDAO();
            pedidoDAO.excluirPedidoComProdutos(idPedidoSelecionado);

            carregarPedidosDoCliente(idCliente); // Atualiza tabela
            JOptionPane.showMessageDialog(this, "Pedido e seus produtos excluídos com sucesso.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Erro ao excluir o pedido: " + ex.getMessage());
            ex.printStackTrace();
        }}
    }//GEN-LAST:event_excluirPedidoSelecionadoActionPerformed

