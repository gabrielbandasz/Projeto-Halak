    private void BtnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnExcluirActionPerformed
        try {
            int row = tabelaProdutos.getSelectedRow();
            if (row == -1) {
                JOptionPane.showMessageDialog(null, "Selecione um produto para excluir.");
                return;
            }

            // Pegando a referência da coluna 0
            Object valorCelula = tabelaProdutos.getValueAt(row, 0);
            if (valorCelula == null) {
                JOptionPane.showMessageDialog(null, "Referência não encontrada na linha selecionada.");
                return;
            }

            String referencia = valorCelula.toString();

            int confirm = JOptionPane.showConfirmDialog(null, "Deseja realmente excluir este produto?", "Confirmação", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                ProdutoDAO produtoDAO = new ProdutoDAO();
                produtoDAO.excluirProduto(referencia, idPedido);

                carregarProdutosNaTabela(); // Atualiza a lista
                JOptionPane.showMessageDialog(null, "Produto excluído com sucesso.");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Erro ao excluir o produto: " + e.getMessage());
            e.printStackTrace();
        }

    }//GEN-LAST:event_BtnExcluirActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        try {
            // Obtém a referência do campo de texto
            String referencia = txtReferencia.getText().trim();

            // Verifica se a referência não está vazia
            if (referencia.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Por favor, insira uma referência válida.");
                return;
            }

            // Cria uma instância do ProdutoDAO
            ProdutoDAO produtoDAO = new ProdutoDAO();

            // Busca o produto pela referência
            Produto p = produtoDAO.buscarPorReferencia(referencia);

            // Verifica se o produto foi encontrado
            if (p != null) {
                // Preenche os campos de texto com os dados do produto
                txtProduto.setText(p.getProduto());
                txtSuperficie.setText(p.getSuperficie());
                txtColecao.setText(p.getColecao());
                txtFormato.setText(p.getFormato());
                txtLocalUso.setText(p.getLocalUso());

                txtM2Pallet.setText(String.format("%.2f", p.getM2Pallet()));
                txtKgM2.setText(String.format("%.2f", p.getKgM2()));
                txtM2Caixa.setText(String.format("%.2f", p.getM2Caixa()));
                txtPcsCaixa.setText(String.valueOf(p.getPcsCaixa()));
                txtValorPalletizado.setText(String.format("%.2f", p.getValorPalletizado()));
            } else {
                // Se o produto não for encontrado, exibe uma mensagem
                JOptionPane.showMessageDialog(null, "Produto não encontrado!");
            }
        } catch (Exception ex) {
            // Em caso de erro, exibe a exceção
            JOptionPane.showMessageDialog(null, "Erro ao buscar produto: " + ex.getMessage());
            ex.printStackTrace();
        }

                }//GEN-LAST:event_btnBuscarActionPerformed

