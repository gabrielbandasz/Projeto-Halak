    private void btnFinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarActionPerformed
           if (idPedido != -1) { // Verifica se o pedido foi criado com sucesso
    try {
        PedidoDAO pedidoDAO = new PedidoDAO();

        // Buscar o pedido com base no ID
        Pedido pedido = pedidoDAO
                .listarPedidosPorCliente(idCliente)
                .stream()
                .filter(p -> p.getIdPedido() == idPedido)
                .findFirst()
                .orElse(null);

        if (pedido != null) {
            // Exibe os dados do pedido nos campos correspondentes
            txtReferencia.setText(String.valueOf(pedido.getIdPedido()));
            txtDataPedido.setText(new SimpleDateFormat("dd/MM/yyyy").format(pedido.getDataPedido()));
            

            // Atualiza a tabela com os produtos deste pedido
            carregarProdutosNaTabela();
            JOptionPane.showMessageDialog(this, "Pedido Finalizado");
        } else {
            JOptionPane.showMessageDialog(this, "Erro: Pedido não encontrado.");
        }
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Erro ao acessar o banco de dados: " + ex.getMessage());
        ex.printStackTrace();
    }
} else {
    JOptionPane.showMessageDialog(this, "Nenhum pedido foi criado. Verifique os dados.");
}


    }//GEN-LAST:event_btnFinalizarActionPerformed

