    private void carregarProdutosNaTabela() {
        if (idPedido == -1) {
            return; // ainda não há pedido criado, então não carrega produtos
        }
        try {
            PedidoDAO pedidoDAO = new PedidoDAO();
            List<Produto> produtos = pedidoDAO.listarProdutosDoPedido(idPedido);

            DefaultTableModel modelo = (DefaultTableModel) tabelaProdutos.getModel();
            modelo.setRowCount(0);

            for (Produto p : produtos) {
                modelo.addRow(new Object[]{
                    p.getReferencia(),
                    p.getProduto(),
                    p.getSuperficie(),
                    p.getColecao(),
                    p.getFormato(),
                    p.getLocalUso(),
                    p.getM2Pallet(),
                    p.getKgM2(),
                    p.getM2Caixa(),
                    p.getPcsCaixa(),
                    p.getValorPalletizado()
                });
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar produtos: " + ex.getMessage());
        }
    }

    private void recarregarTabelaProdutos() {
        carregarProdutosNaTabela();
    }

