    private void listarClientes() {
        DefaultTableModel modelo = (DefaultTableModel) tabelaClientes.getModel();
        modelo.setRowCount(0); // limpa a tabela

        // Obtém a lista e ordena pela razão social
        List<Usuario> lista = dao.listarTodos();
        lista.sort((u1, u2) -> u1.getRazaoSocial().compareToIgnoreCase(u2.getRazaoSocial()));

        for (Usuario c : lista) {
            modelo.addRow(new Object[]{
                c.getId(),
                c.getRazaoSocial(),
                c.getNomeFantasia(),
                c.getCnpj(),
                c.getInscricaoEstadual(),
                c.getEndereco(),
                c.getBairroCidadeEstado(),
                c.getCep(),
                c.getFone(),
                c.getFax(),
                c.getContato()
            });
        }
    }

