    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        if (idSelecionado == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um cliente na tabela para atualizar.");
            return;
        }

        Usuario u = new Usuario();
        u.setId(idSelecionado); // importante!
        u.setRazaoSocial(txtRazaoSocial.getText());
        u.setNomeFantasia(txtNomeFantasia.getText());
        u.setCnpj(txtCnpj.getText());
        u.setInscricaoEstadual(txtInscricaoEstadual.getText());
        u.setEndereco(txtEndereco.getText());
        u.setBairroCidadeEstado(txtBairroCidadeEstado.getText());
        u.setCep(txtCep.getText());
        u.setFone(txtFone.getText());
        u.setFax(txtFax.getText());
        u.setContato(txtContato.getText());

        ClienteDAO dao = new ClienteDAO();
        boolean sucesso = dao.atualizar(u);

        if (sucesso) {
            JOptionPane.showMessageDialog(this, "Cliente atualizado com sucesso!");
            listarClientes();   // atualiza a tabela com os dados do banco
            limparCampos();     // limpa os campos do formulário
            idSelecionado = -1; // reseta o ID
        } else {
            JOptionPane.showMessageDialog(this, "Erro ao atualizar cliente.");
        }

    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idSelecionado == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um cliente para excluir.");
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir o cliente?", "Confirmação", JOptionPane.YES_NO_OPTION);
        if (confirmacao != JOptionPane.YES_OPTION) {
            return;
        }

        ClienteDAO dao = new ClienteDAO();
        boolean sucesso = dao.excluir(idSelecionado);

        if (sucesso) {
            JOptionPane.showMessageDialog(this, "Cliente excluído com sucesso!");

            // Atualiza a tabela
            DefaultTableModel modelo = (DefaultTableModel) tabelaClientes.getModel();
            modelo.setRowCount(0);
            for (Usuario c : dao.listarTodos()) {
                modelo.addRow(new Object[]{
                    c.getId(),
                    c.getRazaoSocial(),
                    c.getNomeFantasia(),
                    c.getCnpj(),
                    c.getInscricaoEstadual(),
                    c.getEndereco(),
                    c.getBairroCidadeEstado(),
                    c.getCep(),
                    c.getFone(),
                    c.getFax(),
                    c.getContato()
                });
            }

            // Limpa os campos
            txtRazaoSocial.setText("");
            txtNomeFantasia.setText("");
            txtCnpj.setText("");
            txtInscricaoEstadual.setText("");
            txtEndereco.setText("");
            txtBairroCidadeEstado.setText("");
            txtCep.setText("");
            txtFone.setText("");
            txtFax.setText("");
            txtContato.setText("");
            idSelecionado = -1;
        } else {
            JOptionPane.showMessageDialog(this, "Erro ao excluir cliente.");
        }    }//GEN-LAST:event_btnExcluirActionPerformed

