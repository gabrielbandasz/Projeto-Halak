    private void filtrarClientes(String texto) {
        DefaultTableModel modelo = (DefaultTableModel) tabelaClientes.getModel();
        modelo.setRowCount(0); // limpa a tabela

        for (Usuario c : dao.listarTodos()) {
            if (c.getRazaoSocial().toLowerCase().contains(texto.toLowerCase())
                    || c.getBairroCidadeEstado().toLowerCase().contains(texto.toLowerCase())) {

                modelo.addRow(new Object[]{
                    c.getId(),
                    c.getRazaoSocial(),
                    c.getNomeFantasia(),
                    c.getCnpj(),
                    c.getInscricaoEstadual(),
                    c.getEndereco(),
                    c.getBairroCidadeEstado(),
                    c.getCep(),
                    c.getFone(),
                    c.getFax(),
                    c.getContato()
                });

            }
        }
    }

